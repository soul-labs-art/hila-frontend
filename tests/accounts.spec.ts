import { test, expect, type APIRequestContext, type Page } from '@playwright/test'
import { mkdir } from 'node:fs/promises'

const password = 'Una frase de pruebas 2026!'
const mailpit = process.env.E2E_MAILPIT_URL ?? 'http://127.0.0.1:8025'
async function mailLink(request: APIRequestContext, email: string, purpose = 'verificar-correo') {
  let link = ''
  await expect.poll(async () => {
    const data = await (await request.get(`${mailpit}/api/v1/search?query=${encodeURIComponent(`to:${email}`)}`)).json()
    for (const message of data.messages ?? []) {
      const body = await (await request.get(`${mailpit}/api/v1/message/${message.ID}`)).json()
      const found = `${body.Text ?? ''} ${body.HTML ?? ''}`.match(new RegExp(`https?://[^\\s<>"']+/${purpose}#token=[^\\s<>"']+`))
      if (found) { link = found[0]; return true }
    }
    return false
  }, { timeout: 30_000, message: `Correo ${purpose} entregado por outbox a Mailpit` }).toBe(true)
  return link
}
async function register(page: Page, email: string, name: string) {
  await page.goto('/registro')
  await page.getByLabel('Tu nombre', { exact: true }).fill(name)
  await page.getByLabel('Correo electrónico', { exact: true }).fill(email)
  await page.getByLabel('Contraseña', { exact: true }).fill(password)
  await page.getByRole('checkbox', { name: 'Soy mayor de 18 años.' }).check()
  await page.getByRole('checkbox', { name: /He leído y acepto/ }).check()
  await page.getByRole('button', { name: 'Crear mi cuenta', exact: true }).click()
  await expect(page).toHaveURL(/registro\/enviado$/)
  const url = await mailLink(page.request, email)
  await page.goto(url)
  await expect(page).not.toHaveURL(/#token=/)
  await page.getByRole('button', { name: 'Verificar mi correo', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Tu correo está verificado')
}
async function login(page: Page, email: string, secret = password) {
  await page.goto('/ingresar')
  await page.getByLabel('Correo electrónico', { exact: true }).fill(email)
  await page.getByLabel('Contraseña', { exact: true }).fill(secret)
  await page.getByRole('button', { name: 'Ingresar', exact: true }).click()
  await expect(page).toHaveURL(/mi-cuenta$/)
}
async function capture(page: Page, name: string) {
  await mkdir('.impeccable/review', { recursive: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.evaluate(() => { if (document.activeElement instanceof HTMLElement) document.activeElement.blur(); window.scrollTo(0, 0) })
  await page.screenshot({ path: `.impeccable/review/${name}-desktop.png`, fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.evaluate(() => window.scrollTo(0, 0))
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: `.impeccable/review/${name}-mobile.png`, fullPage: true })
}

test('cuenta, correo, perfil privado/público, imágenes y recuperación contra API real', async ({ page, browser }) => {
  const email = `volunteer-${Date.now()}@example.test`
  await register(page, email, 'Persona de prueba')
  await login(page, email)
  await page.getByRole('link', { name: 'Crear mi perfil', exact: true }).click()
  await page.getByLabel('Presentación', { exact: true }).fill('Me gusta compartir conocimientos y aprender con mi comunidad.')
  await page.getByLabel('Profesión u oficio (opcional)').fill('Docencia')
  await page.getByLabel('Nivel educativo (opcional y privado)').fill('Información privada de prueba')
  await page.getByLabel('Modalidad preferida').selectOption('HYBRID')
  await page.getByRole('button', { name: 'Guardar perfil', exact: true }).click()
  await expect(page.getByText('Perfil privado', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('Docencia', { exact: true })).toBeVisible()
  await page.getByLabel('Elegir foto', { exact: true }).setInputFiles('public/brand/hila-emblema.png')
  await page.getByRole('button', { name: 'Guardar imagen', exact: true }).first().click()
  await expect(page.getByText('Imagen guardada.', { exact: true })).toBeVisible()
  await page.getByLabel('Elegir portada', { exact: true }).setInputFiles('public/brand/hila-wordmark-delgado.png')
  await page.getByRole('button', { name: 'Guardar imagen', exact: true }).nth(1).click()
  await expect(page.getByText('Imagen guardada.', { exact: true })).toHaveCount(2)
  await page.getByRole('button', { name: 'Publicar perfil', exact: true }).click()
  await expect(page.getByText('Perfil público', { exact: true })).toBeVisible()
  await capture(page, 'volunteer')
  const publicPath = await page.getByRole('link', { name: 'Ver perfil público' }).getAttribute('href')
  const visitor = await browser.newContext()
  const publicPage = await visitor.newPage()
  await publicPage.goto(`http://127.0.0.1:5173${publicPath}`)
  await expect(publicPage.getByRole('heading', { name: 'Persona de prueba', exact: true })).toBeVisible()
  await expect(publicPage.getByText(email, { exact: true })).toHaveCount(0)
  await expect(publicPage.getByText('Información privada de prueba')).toHaveCount(0)
  const publicAvatar = await publicPage.locator('.profile-avatar img').getAttribute('src')
  await capture(publicPage, 'public-volunteer')
  await page.getByRole('button', { name: 'Ocultar perfil', exact: true }).click()
  await expect(page.getByText('Perfil privado', { exact: true })).toBeVisible()
  await publicPage.reload()
  await expect(publicPage.getByRole('heading', { name: 'Este perfil no está disponible.' })).toBeVisible()
  expect((await visitor.request.get(`http://127.0.0.1:5173${publicAvatar}`)).status()).toBe(404)
  await visitor.close()
  await page.getByRole('button', { name: 'Salir', exact: true }).click()
  await page.getByRole('link', { name: 'Olvidé mi contraseña' }).click()
  await page.getByLabel('Correo electrónico', { exact: true }).fill(email)
  await page.getByRole('button', { name: 'Enviar enlace', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('te enviaremos un enlace')
  await page.goto(await mailLink(page.request, email, 'restablecer-acceso'))
  await page.getByLabel('Nueva contraseña', { exact: true }).fill(`${password} nueva`)
  await page.getByLabel('Repite la nueva contraseña', { exact: true }).fill(`${password} nueva`)
  await page.getByRole('button', { name: 'Guardar contraseña', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('nueva contraseña')
  await login(page, email, `${password} nueva`)
  await expect(page.getByRole('heading', { name: /Qué bueno encontrarte/ })).toBeVisible()
})

test('organización: registro, revisión administrativa, publicación y ocultación', async ({ page, browser }) => {
  test.skip(!process.env.E2E_ADMIN_EMAIL || !process.env.E2E_ADMIN_PASSWORD, 'Configura una cuenta ADMIN verificada mediante el bootstrap interno para ejecutar la revisión.')
  const email = `organization-${Date.now()}@example.test`, orgName = `Colectivo de prueba ${Date.now()}`
  await register(page, email, 'Representante de prueba')
  await login(page, email)
  await page.getByRole('link', { name: 'Ver mis organizaciones', exact: true }).click()
  await page.getByRole('link', { name: 'Registrar organización', exact: true }).click()
  await page.getByLabel('Nombre de la organización').fill(orgName)
  await page.getByLabel('Tipo de organización').selectOption('COLLECTIVE')
  await page.getByLabel('Presentación de la organización').fill('Actividades comunitarias de prueba para acompañar el piloto.')
  await page.getByLabel('Trayectoria y referencias del colectivo').fill('Contexto privado de revisión de prueba.')
  await page.getByLabel('Correo público (opcional)').fill('contacto@example.test')
  await page.getByRole('button', { name: 'Registrar y solicitar revisión', exact: true }).click()
  await expect(page).toHaveURL(/organizaciones\/[^/]+\/editar$/)
  await expect(page.getByRole('button', { name: 'Publicar perfil', exact: true })).toBeDisabled()
  const orgPath = new URL(page.url()).pathname, orgId = orgPath.split('/')[2]
  const adminContext = await browser.newContext(), admin = await adminContext.newPage()
  await login(admin, process.env.E2E_ADMIN_EMAIL!, process.env.E2E_ADMIN_PASSWORD!)
  await admin.goto(`/admin/organizaciones/${orgId}`)
  await admin.getByLabel('Decisión', { exact: true }).selectOption('MORE_INFO')
  await admin.getByLabel('Motivo de la decisión').fill('Amplía las referencias de su trabajo territorial.')
  await admin.getByRole('button', { name: 'Registrar decisión', exact: true }).click()
  await expect(admin.getByRole('status')).toContainText('decisión quedó registrada')
  await page.reload()
  await page.getByLabel('Información adicional para la revisión').fill('Referencias adicionales de prueba, sin datos reales.')
  await page.getByRole('button', { name: 'Reenviar a revisión', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('nueva revisión')
  await admin.reload()
  await admin.getByLabel('Decisión', { exact: true }).selectOption('APPROVED')
  await admin.getByLabel('Motivo de la decisión').fill('Información suficiente para el piloto de prueba.')
  await admin.getByRole('button', { name: 'Registrar decisión', exact: true }).click()
  await expect(admin.getByRole('status')).toContainText('decisión quedó registrada')
  await expect(admin.getByLabel('Motivo de la decisión')).toHaveValue('')
  await capture(admin, 'admin')
  await page.reload()
  await page.getByRole('button', { name: 'Publicar perfil', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Ver perfil público' })).toBeVisible()
  await capture(page, 'organization')
  const visitor = await browser.newContext(), publicPage = await visitor.newPage()
  await publicPage.goto(`/organizaciones/${orgId}`)
  await expect(publicPage.getByRole('heading', { name: orgName })).toBeVisible()
  await expect(publicPage.getByText('Contexto privado de revisión de prueba.')).toHaveCount(0)
  await expect(publicPage.getByRole('link', { name: 'Escribir a la organización' })).toHaveAttribute('href', 'mailto:contacto@example.test')
  await capture(publicPage, 'public-organization')
  await admin.getByLabel('Decisión', { exact: true }).selectOption('SUSPENDED')
  await admin.getByLabel('Motivo de la decisión').fill('Suspensión de prueba para verificar privacidad.')
  await admin.getByRole('button', { name: 'Registrar decisión', exact: true }).click()
  await expect(admin.getByRole('status')).toContainText('decisión quedó registrada')
  await publicPage.reload()
  await expect(publicPage.getByRole('heading', { name: 'Este perfil no está disponible.' })).toBeVisible()
  await adminContext.close(); await visitor.close()
})

